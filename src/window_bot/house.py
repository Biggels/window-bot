"""A deliberately small model of how the house responds to open or closed windows.

The model tracks four things on a fixed time step:

* indoor temperature: drifts toward outdoors (quickly when open, slowly when
  closed) and is held between the heat and cool setpoints by the HVAC, which
  is assumed to be off whenever the windows are open;
* moisture in the air: exchanged with outdoor air at the open or closed air
  change rate, plus moisture generated by occupants, minus what the AC coil
  removes while it is cooling;
* moisture stored in materials (drywall, furniture, fabrics): exchanges with
  the air over a few hours. This is why a short airing produces a
  spike in air humidity that mostly fades after the windows close, and why a
  long humid stretch takes a while to dry back out;
* staleness: a CO2-like indoor pollutant scaled so 1.0 is a house that has
  been closed for a long time and 0.0 is outdoor air. Fresh air value is
  measured as reductions in staleness.

The constants below are reasonable starting points, not measurements of any
particular house. An indoor temperature/humidity/CO2 sensor is the way to
calibrate them; `IndoorState` is the seam where a reading would replace the
estimated starting state.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
import math
from typing import Sequence

from .psychrometrics import (
    humidity_ratio_from_dew_point,
    humidity_ratio_from_relative_humidity,
    relative_humidity,
)

STEP = timedelta(minutes=15)
STEP_HOURS = STEP.total_seconds() / 3600.0

AIR_DENSITY_KG_PER_M3 = 1.2

# Moisture held by interior materials, as a multiple of the air's own capacity,
# and how quickly the materials exchange moisture with the air.
BUFFER_CAPACITY_RATIO = 8.0
BUFFER_TIME_CONSTANT_HOURS = 4.0

# A closed house settles a few degrees above outdoor temperature because of
# occupants, appliances and sun; it gets there slowly.
CLOSED_HOUSE_GAIN_OFFSET_C = 3.0
CLOSED_HOUSE_TIME_CONSTANT_HOURS = 10.0

# With windows open, the house's thermal mass slows the temperature change
# relative to the air change rate.
OPEN_THERMAL_MASS_FACTOR = 8.0

# How fast (degrees C per hour) the AC can counter heat gains at full output.
AC_FULL_OUTPUT_C_PER_HOUR = 1.8

# The AC coil cannot dry air below roughly this dew point, and removes
# moisture faster when indoor air is more humid than the reference condition.
AC_COIL_DEW_POINT_C = 10.0
AC_REFERENCE_RELATIVE_HUMIDITY = 50.0
AC_MAX_HUMIDITY_FACTOR = 1.5


@dataclass(frozen=True)
class HouseParameters:
    heat_setpoint_c: float
    cool_setpoint_c: float
    volume_m3: float
    open_air_changes_per_hour: float
    closed_air_changes_per_hour: float
    moisture_generation_kg_per_day: float
    ac_moisture_removal_kg_per_hour: float

    @property
    def air_mass_kg(self) -> float:
        return self.volume_m3 * AIR_DENSITY_KG_PER_M3


@dataclass(frozen=True)
class IndoorState:
    temperature_c: float
    air_humidity_ratio: float
    buffer_humidity_ratio: float
    staleness: float = 1.0

    @property
    def relative_humidity(self) -> float:
        return relative_humidity(self.temperature_c, self.air_humidity_ratio)

    @classmethod
    def from_reading(
        cls,
        *,
        temperature_c: float,
        relative_humidity_percent: float,
        staleness: float = 1.0,
    ) -> "IndoorState":
        """Build a state from a measured temperature and humidity (materials assumed in equilibrium)."""
        ratio = humidity_ratio_from_relative_humidity(temperature_c, relative_humidity_percent)
        return cls(
            temperature_c=temperature_c,
            air_humidity_ratio=ratio,
            buffer_humidity_ratio=ratio,
            staleness=staleness,
        )


@dataclass(frozen=True)
class OutdoorStep:
    time: datetime
    temperature_c: float
    dew_point_c: float
    humidity_ratio: float
    rain_likely: bool


@dataclass
class Trace:
    """Indoor conditions at the end of each simulated step."""

    temperature_c: list[float]
    relative_humidity: list[float]
    staleness: list[float]
    hvac_load: list[float]
    final_state: IndoorState


def simulate(
    params: HouseParameters,
    initial: IndoorState,
    outdoor: Sequence[OutdoorStep],
    open_flags: Sequence[bool],
) -> Trace:
    """Step the house model forward over ``outdoor`` with windows open where ``open_flags`` is true."""
    dt = STEP_HOURS
    air_mass = params.air_mass_kg
    buffer_mass = air_mass * BUFFER_CAPACITY_RATIO
    coupling = buffer_mass / BUFFER_TIME_CONSTANT_HOURS
    coupling_decay = math.exp(-coupling * (1.0 / air_mass + 1.0 / buffer_mass) * dt)
    open_ach = params.open_air_changes_per_hour
    closed_ach = params.closed_air_changes_per_hour
    open_exchange_decay = math.exp(-open_ach * dt)
    closed_exchange_decay = math.exp(-closed_ach * dt)
    open_temperature_decay = math.exp(-open_ach / OPEN_THERMAL_MASS_FACTOR * dt)
    closed_temperature_decay = math.exp(-dt / CLOSED_HOUSE_TIME_CONSTANT_HOURS)
    open_staleness_floor = closed_ach / open_ach
    generation_per_step = params.moisture_generation_kg_per_day / 24.0 * dt / air_mass
    max_removal_per_step = params.ac_moisture_removal_kg_per_hour * dt / air_mass
    max_ac_drift = AC_FULL_OUTPUT_C_PER_HOUR * dt
    heat_sp = params.heat_setpoint_c
    cool_sp = params.cool_setpoint_c
    coil_ratio = humidity_ratio_from_dew_point(AC_COIL_DEW_POINT_C)
    reference_span = max(
        humidity_ratio_from_relative_humidity(cool_sp, AC_REFERENCE_RELATIVE_HUMIDITY) - coil_ratio,
        1e-4,
    )

    temperature = initial.temperature_c
    w_air = initial.air_humidity_ratio
    w_buffer = initial.buffer_humidity_ratio
    staleness = initial.staleness

    temperatures: list[float] = []
    humidities: list[float] = []
    stalenesses: list[float] = []
    loads: list[float] = []

    for step, is_open in zip(outdoor, open_flags):
        runtime = 0.0
        if is_open:
            target = step.temperature_c
            temperature = target + (temperature - target) * open_temperature_decay
            hvac_load = 0.0
            w_air = step.humidity_ratio + (w_air - step.humidity_ratio) * open_exchange_decay
            staleness = open_staleness_floor + (staleness - open_staleness_floor) * open_exchange_decay
        else:
            target = step.temperature_c + CLOSED_HOUSE_GAIN_OFFSET_C
            free_temperature = target + (temperature - target) * closed_temperature_decay
            if free_temperature > cool_sp:
                excess = free_temperature - cool_sp
                runtime = min(1.0, excess / max_ac_drift)
                temperature = free_temperature - runtime * max_ac_drift
            elif free_temperature < heat_sp:
                temperature = heat_sp
            else:
                temperature = free_temperature
            hvac_load = abs(free_temperature - temperature)
            w_air = step.humidity_ratio + (w_air - step.humidity_ratio) * closed_exchange_decay
            staleness = 1.0 + (staleness - 1.0) * closed_exchange_decay

        equilibrium = (air_mass * w_air + buffer_mass * w_buffer) / (air_mass + buffer_mass)
        w_air = equilibrium + (w_air - equilibrium) * coupling_decay
        w_buffer = equilibrium + (w_buffer - equilibrium) * coupling_decay

        w_air += generation_per_step
        if runtime > 0.0 and w_air > coil_ratio:
            humidity_factor = min((w_air - coil_ratio) / reference_span, AC_MAX_HUMIDITY_FACTOR)
            removal = runtime * max_removal_per_step * humidity_factor
            w_air -= min(removal, w_air - coil_ratio)

        temperatures.append(temperature)
        humidities.append(relative_humidity(temperature, w_air))
        stalenesses.append(staleness)
        loads.append(hvac_load)

    return Trace(
        temperature_c=temperatures,
        relative_humidity=humidities,
        staleness=stalenesses,
        hvac_load=loads,
        final_state=IndoorState(
            temperature_c=temperature,
            air_humidity_ratio=w_air,
            buffer_humidity_ratio=w_buffer,
            staleness=staleness,
        ),
    )


def default_initial_state(params: HouseParameters, outdoor_temperature_c: float) -> IndoorState:
    """A neutral starting guess, used before a spin-up period refines it."""
    temperature = min(max(outdoor_temperature_c, params.heat_setpoint_c), params.cool_setpoint_c)
    return IndoorState.from_reading(temperature_c=temperature, relative_humidity_percent=50.0)
